package com.atrainingtracker.trainingtracker.tracker

import android.os.Build
import com.atrainingtracker.BuildConfig
import org.json.JSONArray
import org.json.JSONObject
import java.io.PrintWriter
import java.io.StringWriter
import java.util.Collections
import java.util.LinkedHashMap

/**
 * Diagnostic stages across the workout recording lifecycle (REQ-TRK-053.2).
 */
enum class DiagnosticStage {
    INIT,
    SAMPLE_WRITE,
    FINALIZE
}

/**
 * Categorized failure cause for user-friendly plain-language explanation (REQ-TRK-053.4).
 */
enum class DiagnosticCategory {
    STORAGE_FULL,
    SAMPLE_WRITE,
    FINALIZE,
    GENERIC
}

/**
 * Structured diagnostic record representing a deduplicated caught exception (REQ-TRK-053.2).
 */
data class DiagnosticErrorEntry(
    val stage: DiagnosticStage,
    val exceptionClass: String,
    val message: String,
    val firstTimestampMs: Long,
    var lastTimestampMs: Long,
    var count: Int,
    val stackTrace: String
)

/**
 * Thread-safe, bounded in-memory diagnostic error collector for active workouts (REQ-TRK-053.2).
 *
 * Captures caught exceptions during table initialization, 1-Hz sample recording,
 * and post-workout session finalization. Deduplicates repeated exceptions by
 * `(stage, exceptionClass, message)` and caps total payload size at 8 KB to prevent database bloat.
 */
class WorkoutRecordingErrorCollector {

    companion object {
        const val MAX_PAYLOAD_BYTES: Int = 8192
        private const val MAX_STACK_TRACE_LINES: Int = 12

        /**
         * Resolves the user-facing explanation category from structured diagnostic entries.
         */
        @JvmStatic
        fun resolvePrimaryCauseCategory(entries: List<DiagnosticErrorEntry>): DiagnosticCategory {
            if (entries.isEmpty()) return DiagnosticCategory.GENERIC

            val hasStorageFull = entries.any { entry ->
                entry.exceptionClass.contains("SQLiteFullException", ignoreCase = true) ||
                        entry.message.contains("disk full", ignoreCase = true) ||
                        entry.message.contains("database or disk is full", ignoreCase = true)
            }
            if (hasStorageFull) {
                return DiagnosticCategory.STORAGE_FULL
            }

            val hasSampleWrite = entries.any { it.stage == DiagnosticStage.SAMPLE_WRITE }
            if (hasSampleWrite) {
                return DiagnosticCategory.SAMPLE_WRITE
            }

            val allFinalize = entries.all { it.stage == DiagnosticStage.FINALIZE }
            if (allFinalize) {
                return DiagnosticCategory.FINALIZE
            }

            return DiagnosticCategory.GENERIC
        }

        /**
         * Parses a JSON string generated by [toJson] into a list of [DiagnosticErrorEntry].
         */
        @JvmStatic
        fun fromJson(jsonStr: String?): List<DiagnosticErrorEntry> {
            if (jsonStr.isNullOrBlank()) return emptyList()
            val list = mutableListOf<DiagnosticErrorEntry>()
            try {
                val array = JSONArray(jsonStr)
                for (i in 0 until array.length()) {
                    val obj = array.getJSONObject(i)
                    val stageStr = obj.optString("stage", DiagnosticStage.SAMPLE_WRITE.name)
                    val stage = try {
                        DiagnosticStage.valueOf(stageStr)
                    } catch (e: Exception) {
                        DiagnosticStage.SAMPLE_WRITE
                    }
                    list.add(
                        DiagnosticErrorEntry(
                            stage = stage,
                            exceptionClass = obj.optString("exceptionClass", "UnknownException"),
                            message = obj.optString("message", ""),
                            firstTimestampMs = obj.optLong("firstTimestampMs", 0L),
                            lastTimestampMs = obj.optLong("lastTimestampMs", 0L),
                            count = obj.optInt("count", 1),
                            stackTrace = obj.optString("stackTrace", "")
                        )
                    )
                }
            } catch (e: Exception) {
                list.add(
                    DiagnosticErrorEntry(
                        stage = DiagnosticStage.SAMPLE_WRITE,
                        exceptionClass = "UnparseablePayloadException",
                        message = jsonStr.take(200),
                        firstTimestampMs = System.currentTimeMillis(),
                        lastTimestampMs = System.currentTimeMillis(),
                        count = 1,
                        stackTrace = ""
                    )
                )
            }
            return list
        }

        /**
         * Sanitizes a stack trace to the top N frames to avoid memory and storage bloat.
         */
        @JvmStatic
        fun sanitizeStackTrace(throwable: Throwable?): String {
            if (throwable == null) return ""
            val sw = StringWriter()
            val pw = PrintWriter(sw)
            throwable.printStackTrace(pw)
            val fullTrace = sw.toString()
            val lines = fullTrace.lines()
            return if (lines.size > MAX_STACK_TRACE_LINES) {
                lines.take(MAX_STACK_TRACE_LINES).joinToString("\n") + "\n\t... (${lines.size - MAX_STACK_TRACE_LINES} more frames)"
            } else {
                fullTrace
            }
        }

        /**
         * Formats a pre-filled email bug report body including device and app metadata.
         */
        @JvmStatic
        fun formatEmailBody(
            workoutName: String,
            sportName: String,
            recordingErrorsJson: String?
        ): String {
            val sb = StringBuilder()
            sb.append("=== aTrainingTracker Fehlerbericht ===\n\n")
            sb.append("App Version: ").append(BuildConfig.VERSION_NAME).append(" (").append(BuildConfig.VERSION_CODE).append(")\n")
            sb.append("Gerät: ").append(Build.MANUFACTURER).append(" ").append(Build.MODEL).append("\n")
            sb.append("Android: ").append(Build.VERSION.RELEASE).append(" (API ").append(Build.VERSION.SDK_INT).append(")\n")
            sb.append("Training: ").append(workoutName).append(" (").append(sportName).append(")\n")
            sb.append("Zeitstempel: ").append(System.currentTimeMillis()).append("\n\n")
            sb.append("--- Diagnose-Protokoll ---\n")
            if (recordingErrorsJson.isNullOrBlank()) {
                sb.append("Keine Fehlerdetails vorhanden.\n")
            } else {
                val entries = fromJson(recordingErrorsJson)
                entries.forEachIndexed { index, entry ->
                    sb.append("\n[#").append(index + 1).append(" - ").append(entry.stage.name).append("]\n")
                    sb.append("Ausnahme: ").append(entry.exceptionClass).append("\n")
                    sb.append("Nachricht: ").append(entry.message).append("\n")
                    sb.append("Häufigkeit: ").append(entry.count).append("x\n")
                    sb.append("Erstes Auftreten: ").append(entry.firstTimestampMs).append("\n")
                    sb.append("Letztes Auftreten: ").append(entry.lastTimestampMs).append("\n")
                    if (entry.stackTrace.isNotBlank()) {
                        sb.append("Stack Trace:\n").append(entry.stackTrace).append("\n")
                    }
                }
            }
            sb.append("\n======================================\n")
            return sb.toString()
        }
    }

    private val errorMap = Collections.synchronizedMap(LinkedHashMap<Triple<DiagnosticStage, String, String>, DiagnosticErrorEntry>())

    /**
     * Records a caught exception or failure message.
     *
     * @return `true` if this is a newly registered distinct error or if the count reached
     * a reporting interval (1, 10, 50, 100, 200, ...), indicating that callers should update the DB.
     */
    @Synchronized
    fun record(
        stage: DiagnosticStage,
        throwable: Throwable?,
        customMessage: String? = null
    ): Boolean {
        val now = System.currentTimeMillis()
        val exceptionClass = throwable?.javaClass?.name ?: "DiagnosticMessage"
        val rawMessage = customMessage ?: throwable?.message ?: "Unknown error"
        val sanitizedMessage = rawMessage.take(250)
        val key = Triple(stage, exceptionClass, sanitizedMessage)

        val existing = errorMap[key]
        return if (existing != null) {
            existing.lastTimestampMs = now
            existing.count++
            shouldTriggerDbSync(existing.count)
        } else {
            val trace = sanitizeStackTrace(throwable)
            errorMap[key] = DiagnosticErrorEntry(
                stage = stage,
                exceptionClass = exceptionClass,
                message = sanitizedMessage,
                firstTimestampMs = now,
                lastTimestampMs = now,
                count = 1,
                stackTrace = trace
            )
            true
        }
    }

    private fun shouldTriggerDbSync(count: Int): Boolean {
        return count == 1 || count == 10 || count == 50 || count % 100 == 0
    }

    @Synchronized
    fun getEntries(): List<DiagnosticErrorEntry> {
        return errorMap.values.toList()
    }

    @Synchronized
    fun isEmpty(): Boolean = errorMap.isEmpty()

    @Synchronized
    fun clear() {
        errorMap.clear()
    }

    /**
     * Serializes all recorded diagnostic entries to a compact JSON string, capped at [MAX_PAYLOAD_BYTES].
     */
    @Synchronized
    fun toJson(): String? {
        if (errorMap.isEmpty()) return null

        val array = JSONArray()
        for (entry in errorMap.values) {
            val obj = JSONObject().apply {
                put("stage", entry.stage.name)
                put("exceptionClass", entry.exceptionClass)
                put("message", entry.message)
                put("firstTimestampMs", entry.firstTimestampMs)
                put("lastTimestampMs", entry.lastTimestampMs)
                put("count", entry.count)
                if (entry.stackTrace.isNotBlank()) {
                    put("stackTrace", entry.stackTrace)
                }
            }
            array.put(obj)
        }

        var json = array.toString()
        if (json.toByteArray(Charsets.UTF_8).size > MAX_PAYLOAD_BYTES) {
            // Drop stack traces if payload exceeds size limit
            val fallbackArray = JSONArray()
            for (entry in errorMap.values) {
                val obj = JSONObject().apply {
                    put("stage", entry.stage.name)
                    put("exceptionClass", entry.exceptionClass)
                    put("message", entry.message)
                    put("firstTimestampMs", entry.firstTimestampMs)
                    put("lastTimestampMs", entry.lastTimestampMs)
                    put("count", entry.count)
                }
                fallbackArray.put(obj)
            }
            json = fallbackArray.toString()
            if (json.toByteArray(Charsets.UTF_8).size > MAX_PAYLOAD_BYTES) {
                json = json.take(MAX_PAYLOAD_BYTES - 20) + "\"...[TRUNCATED]\"]"
            }
        }
        return json
    }
}
