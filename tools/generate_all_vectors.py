#!/usr/bin/env python3
import os
import math
from PIL import Image

def rdp(points, epsilon):
    if len(points) <= 2:
        return points
    start = points[0]
    end = points[-1]
    dmax = 0.0
    index = 0
    dx = end[0] - start[0]
    dy = end[1] - start[1]
    mag = math.hypot(dx, dy)
    for i in range(1, len(points) - 1):
        p = points[i]
        if mag == 0:
            d = math.hypot(p[0] - start[0], p[1] - start[1])
        else:
            d = abs(dy * p[0] - dx * p[1] + end[0] * start[1] - end[1] * start[0]) / mag
        if d > dmax:
            dmax = d
            index = i
    if dmax > epsilon:
        res1 = rdp(points[:index+1], epsilon)
        res2 = rdp(points[index:], epsilon)
        return res1[:-1] + res2
    else:
        return [start, end]

def get_loops_for_mask(mask):
    h = len(mask)
    w = len(mask[0])
    segments = []
    for y in range(h - 1):
        for x in range(w - 1):
            tl = 1 if mask[y][x] else 0
            tr = 1 if mask[y][x+1] else 0
            br = 1 if mask[y+1][x+1] else 0
            bl = 1 if mask[y+1][x] else 0
            case = (tl << 3) | (tr << 2) | (br << 1) | bl
            top = (x + 0.5, y)
            right = (x + 1, y + 0.5)
            bottom = (x + 0.5, y + 1)
            left = (x, y + 0.5)
            if case == 1 or case == 14:
                segments.append((bottom, left))
            elif case == 2 or case == 13:
                segments.append((right, bottom))
            elif case == 3 or case == 12:
                segments.append((right, left))
            elif case == 4 or case == 11:
                segments.append((top, right))
            elif case == 5:
                segments.append((top, right))
                segments.append((bottom, left))
            elif case == 10:
                segments.append((top, left))
                segments.append((right, bottom))
            elif case == 6 or case == 9:
                segments.append((top, bottom))
            elif case == 7 or case == 8:
                segments.append((top, left))
    from collections import defaultdict
    adj = defaultdict(list)
    for p1, p2 in segments:
        adj[p1].append(p2)
        adj[p2].append(p1)
    loops = []
    visited_edges = set()
    for start in list(adj.keys()):
        for nxt in adj[start]:
            edge = tuple(sorted((start, nxt)))
            if edge in visited_edges:
                continue
            visited_edges.add(edge)
            loop = [start, nxt]
            curr = nxt
            prev = start
            while True:
                neighbors = [nb for nb in adj[curr] if nb != prev]
                if not neighbors:
                    break
                next_pt = neighbors[0]
                edge2 = tuple(sorted((curr, next_pt)))
                if edge2 in visited_edges:
                    break
                visited_edges.add(edge2)
                loop.append(next_pt)
                prev, curr = curr, next_pt
                if curr == start:
                    break
            if len(loop) > 6 and loop[0] == loop[-1]:
                loops.append(loop)
    return loops

def format_path(loops, eps=1.0):
    parts = []
    for l in loops:
        l_adj = [(p[0] - 1.0, p[1] - 1.0) for p in l]
        s = rdp(l_adj, eps)
        if len(s) < 3:
            continue
        p_str = f"M{s[0][0]:.1f},{s[0][1]:.1f}" + "".join(f"L{p[0]:.1f},{p[1]:.1f}" for p in s[1:-1]) + "Z"
        parts.append(p_str)
    return "".join(parts)

def extract_path(img_path, filter_fn, eps=1.0):
    img = Image.open(img_path).convert('RGBA')
    w, h = img.size
    mask = [[False]*(w+2) for _ in range(h+2)]
    for y in range(h):
        for x in range(w):
            if filter_fn(img.getpixel((x, y))):
                mask[y+1][x+1] = True
    return format_path(get_loops_for_mask(mask), eps)

def write_vector(out_path, width, height, vp_w, vp_h, paths, source_desc=""):
    """
    paths is a list of tuples: (fill_color, path_data)
    """
    xml = [
        '<!--',
        '  Generated by tools/generate_all_vectors.py from legacy reference raster asset.',
        f'  Source Reference: {source_desc}',
        '  Invariant: Faithful multi-color vector geometry / technical protocol badge emblem (REQ-UI-375).',
        '-->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{width}dp"',
        f'    android:height="{height}dp"',
        f'    android:viewportWidth="{vp_w}"',
        f'    android:viewportHeight="{vp_h}">',
    ]
    for fill_color, path_data in paths:
        if path_data:
            xml.append('    <path')
            xml.append(f'        android:fillColor="{fill_color}"')
            xml.append(f'        android:pathData="{path_data}" />')
    xml.append('</vector>\n')
    
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write("\n".join(xml))
    print(f"Generated: {out_path}")

